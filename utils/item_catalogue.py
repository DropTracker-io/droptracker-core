"""Item names and stack-size sprite variants, read from the game cache.

Both of the things this answers used to be answered from the ``items`` table,
and both were wrong in the same way. ``items`` is not a catalogue — it only
holds what somebody has *submitted* — so it knows nothing about an item until
it has been dropped. On personal-best loadouts that meant 89 of 95 gear ids had
no row at all, which is precisely the set that also had no icon: the items that
looked broken were the items nothing knew about.

The catalogue is generated by ``scripts/cache/extract-item-catalogue.mjs`` into
``scripts/item_catalogue.json`` and committed, the same way the collection log
structure and the CA task registry are. Regenerate it after a game update.

Two questions it settles:

**Names.** Every id the site can display resolves — measured at 100% of both
the 2,069 ids in real loadouts and the 1,716 collection log slots, against
94.8% from the cache's own name field alone and 95.7% from ``items``. The
difference is noted and placeholder items, which carry no name of their own and
point at the item they stand in for.

**Stack variants.** A stackable item is stored as its single-unit id and the
game swaps to larger pile sprites as the stack grows. The cache carries the
thresholds per item, so this replaces three hand-written copies of the coin
mapping — all of which had the thresholds wrong (10/50/100 where the game
switches at 25/100/250, so 100 coins drew the 250-pile sprite).
"""
from __future__ import annotations

import json
import os
import threading
from typing import Dict, List, Optional, Tuple

_SCRIPTS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts")

#: The committed catalogue: what a fresh checkout (and CI) has.
CATALOGUE_PATH = os.path.join(_SCRIPTS, "item_catalogue.json")
#: Written by ``scripts/refresh_game_cache.py`` whenever the game cache mirror
#: publishes a new build, so production knows an update's items within the
#: hour instead of whenever someone next commits the file. Untracked, and
#: preferred whenever it exists.
LIVE_CATALOGUE_PATH = os.path.join(_SCRIPTS, "cache", "item_catalogue.live.json")
#: Collection log slot ids, to break ties between same-named items.
_CLOG_PATHS = (
    os.path.join(_SCRIPTS, "cache", "collection_log_structure.live.json"),
    os.path.join(_SCRIPTS, "collection_log_structure.json"),
)

# name, and ascending [(threshold, variant_id)] for stackables.
_Entry = Tuple[str, List[Tuple[int, int]]]

_lock = threading.Lock()
_catalogue: Optional[Dict[int, _Entry]] = None
#: folded name -> [(item_id, is_stand_in, is_ge_tradeable)]
_by_name: Dict[str, List[Tuple[int, bool, bool]]] = {}
_meta: Dict[str, object] = {}
_loaded_key: Optional[tuple] = None
_clog_ids: frozenset = frozenset()
_clog_key: Optional[tuple] = None


def _active_path() -> Optional[str]:
    for path in (LIVE_CATALOGUE_PATH, CATALOGUE_PATH):
        if os.path.exists(path):
            return path
    return None


def _fold(name) -> str:
    return " ".join(str(name or "").split()).lower()


def _load() -> Dict[int, _Entry]:
    """The catalogue, reloaded when the file on disk changes.

    The mtime check means a regenerated catalogue is picked up without a service
    restart, which matters because the natural time to regenerate is right after
    a game update — when new item ids are already arriving.
    """
    global _catalogue, _by_name, _meta, _loaded_key
    path = _active_path()
    try:
        key = (path, os.path.getmtime(path)) if path else None
    except OSError:
        key = None
    if key is None:
        # No catalogue on this box: callers degrade to their own fallbacks
        # rather than failing. An empty dict is a valid answer to every query
        # here ("we do not know"), which is what those fallbacks expect.
        return {}
    with _lock:
        if _catalogue is not None and _loaded_key == key:
            return _catalogue
        try:
            with open(path, "r", encoding="utf-8") as fh:
                raw = json.load(fh)
            items = raw.get("items") or {}
            parsed: Dict[int, _Entry] = {}
            by_name: Dict[str, List[Tuple[int, bool, bool]]] = {}
            for key_id, entry in items.items():
                try:
                    item_id = int(key_id)
                except (TypeError, ValueError):
                    continue
                if not isinstance(entry, dict):
                    continue
                name = entry.get("n")
                if not isinstance(name, str) or not name:
                    continue
                variants: List[Tuple[int, int]] = []
                for pair in entry.get("sv") or []:
                    if (
                        isinstance(pair, list)
                        and len(pair) == 2
                        and isinstance(pair[0], int)
                        and isinstance(pair[1], int)
                        and pair[0] >= 2
                        and pair[1] > 0
                    ):
                        variants.append((pair[0], pair[1]))
                variants.sort()
                parsed[item_id] = (name, variants)
                by_name.setdefault(_fold(name), []).append(
                    (item_id, bool(entry.get("x")), bool(entry.get("g"))))
            _catalogue = parsed
            _by_name = by_name
            _meta = {k: v for k, v in raw.items() if k != "items"}
            _loaded_key = key
        except Exception:
            # A corrupt or half-written file must not take the API down.
            _catalogue = _catalogue or {}
        return _catalogue


def _collection_log_ids() -> frozenset:
    """Every collection log slot id, from the newest structure on disk."""
    global _clog_ids, _clog_key
    for path in _CLOG_PATHS:
        try:
            key = (path, os.path.getmtime(path))
        except OSError:
            continue
        if key == _clog_key:
            return _clog_ids
        ids = set()

        def walk(node):
            if isinstance(node, dict):
                listed = node.get("items")
                if isinstance(listed, list):
                    ids.update(i for i in listed if isinstance(i, int))
                for value in node.values():
                    walk(value)
            elif isinstance(node, list):
                for value in node:
                    walk(value)

        try:
            with open(path, "r", encoding="utf-8") as fh:
                walk(json.load(fh))
        except Exception:
            continue
        _clog_ids, _clog_key = frozenset(ids), key
        return _clog_ids
    return frozenset()


def catalogue_info() -> Dict[str, object]:
    """Which game build the loaded catalogue came from (``cache_commit``...)."""
    _load()
    return dict(_meta)


def ids_for_name(name) -> List[int]:
    """Every real item id the game gives ``name`` (case-insensitive), lowest
    first. Noted copies and bank placeholders are left out: they are stand-ins
    for an item, not items. Entries from a catalogue built before those were
    flagged count as real, so an old file still answers."""
    if not _load():
        return []
    return sorted(i for i, stand_in, _ in _by_name.get(_fold(name), ()) if not stand_in)


def canonical_item_id(name) -> Optional[int]:
    """The id to mint for an item known only by name, or None if the game
    has no such item.

    Many ids share a name (a quest copy, a cosmetic variant, a pet's
    metamorphs), so this picks the one the rest of the site means: a
    collection log slot first, then a Grand Exchange tradeable, then the
    lowest id. Measured on 2026-10-20 against the 10,773 names the ``items``
    table and the cache share, it agreed with the stored id on 99.8%; every
    disagreement was a row holding a noted id or a name the table already
    has (which callers look up first, so this never overrides it).
    """
    if not _load():
        return None
    candidates = [(i, ge) for i, stand_in, ge in _by_name.get(_fold(name), ())
                  if not stand_in]
    if not candidates:
        return None
    clog = _collection_log_ids()
    candidates.sort(key=lambda c: (c[0] not in clog, not c[1], c[0]))
    return candidates[0][0]


def name_matches(item_id, name) -> Optional[bool]:
    """Whether the game names ``item_id`` ``name``: True/False, or None when
    the catalogue does not know the id (it predates the item)."""
    known = item_name(item_id)
    if known is None:
        return None
    return _fold(known) == _fold(name)


def item_name(item_id) -> Optional[str]:
    """The game's name for ``item_id``, or None if the catalogue has no entry."""
    try:
        return _load().get(int(item_id), (None, None))[0]
    except (TypeError, ValueError):
        return None


def item_names(item_ids) -> Dict[int, str]:
    """``{item_id: name}`` for the ids the catalogue knows, skipping the rest."""
    catalogue = _load()
    out: Dict[int, str] = {}
    for raw in item_ids or ():
        try:
            item_id = int(raw)
        except (TypeError, ValueError):
            continue
        entry = catalogue.get(item_id)
        if entry:
            out[item_id] = entry[0]
    return out


def stack_display_id(item_id, quantity) -> int:
    """The sprite id the game would draw for ``quantity`` of ``item_id``.

    The largest variant whose threshold the quantity reaches; the base id when
    the item is not stackable, is unknown, or the quantity is below the first
    threshold. Never raises and always returns an int, so callers can use it
    unconditionally in place of the raw id.
    """
    try:
        base = int(item_id)
        count = int(quantity)
    except (TypeError, ValueError):
        return item_id
    entry = _load().get(base)
    if not entry or not entry[1]:
        return base
    display = base
    for threshold, variant_id in entry[1]:
        if count >= threshold:
            display = variant_id
        else:
            break
    return display


def largest_stack_id(item_id) -> Optional[int]:
    """The fullest pile sprite for ``item_id``, or None if it has no variants.

    The loot boards deliberately show the fullest pile regardless of quantity
    (suggestion #44), which is a different policy from :func:`stack_display_id`
    and stays a separate function for that reason — but both read the same
    thresholds, so there is only one place that knows what a stack variant is.
    """
    try:
        entry = _load().get(int(item_id))
    except (TypeError, ValueError):
        return None
    if not entry or not entry[1]:
        return None
    return entry[1][-1][1]


def stack_variant_ids(item_ids=None) -> set:
    """Every variant id reachable from ``item_ids`` (or the whole catalogue).

    The icon sweep needs this: a stack variant is an id the site can render
    without it ever having been submitted, dropped, or worn, so nothing else
    would think to fetch its icon.
    """
    catalogue = _load()
    if item_ids is None:
        sources = catalogue.items()
    else:
        wanted = set()
        for raw in item_ids:
            try:
                wanted.add(int(raw))
            except (TypeError, ValueError):
                continue
        sources = ((i, catalogue[i]) for i in wanted if i in catalogue)
    out = set()
    for _, (_, variants) in sources:
        for _, variant_id in variants:
            out.add(variant_id)
    return out
