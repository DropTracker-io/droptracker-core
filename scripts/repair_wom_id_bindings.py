#!/usr/bin/env python3
"""
Repair incorrect WOM IDs while preserving existing player_ids/history.

This script consumes the output of scripts/wom_id_audit.py and repairs only
true WOM identity mismatches (wom_id_remote != wom_id_stored). It does NOT
rename players. The current local player_name is intentionally retained.

Key behavior:
- Dry-run by default (no writes).
- Per-player transactional repair.
- If target WOM ID already exists on another player row, merge references from
  target row -> source row so historical data remains tied to source player_id.
- Handles duplicate-key collisions on reassignment for unique constraints that
  include player_id by deleting exact duplicates before update.
- Skips risky account_hash conflicts unless manually resolved.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Set, Tuple

from sqlalchemy import inspect, text
from sqlalchemy.exc import SQLAlchemyError

# Allow running directly via `python scripts/repair_wom_id_bindings.py`
PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from db import Session  # noqa: E402
from db.models import Player  # noqa: E402


def parse_args(argv: Optional[Iterable[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Repair incorrect player WOM IDs using WOM audit output.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--audit-file",
        type=Path,
        default=Path("logs/wom_id_audit.json"),
        help="Audit JSON file generated by scripts/wom_id_audit.py",
    )
    parser.add_argument(
        "--report-file",
        type=Path,
        default=Path("logs/wom_id_repair_report.json"),
        help="Path to write repair report JSON",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Apply mutations. Without this flag, script runs in dry-run mode.",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Optional max number of candidate players to process",
    )
    parser.add_argument(
        "--player-id",
        action="append",
        type=int,
        default=None,
        help="Optional specific player_id(s) to process",
    )
    parser.add_argument(
        "--include-detected-via",
        action="append",
        choices=["id_lookup", "username_lookup"],
        default=None,
        help="Filter mismatches by detection method (can pass multiple)",
    )
    parser.add_argument(
        "--include-lookup-failures",
        action="store_true",
        help=(
            "Include lookup_failures entries that contain both wom_id_stored and "
            "resolved wom_id_remote (usually none in current audit output)."
        ),
    )
    return parser.parse_args(argv)


def configure_logging() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
    )


def quote_ident(name: str) -> str:
    return f"`{name.replace('`', '``')}`"


def ensure_parent_dir(path: Path) -> None:
    if not path.parent.exists():
        path.parent.mkdir(parents=True, exist_ok=True)


def parse_iso(ts: Optional[str]) -> datetime:
    if not ts:
        return datetime.min
    try:
        return datetime.fromisoformat(ts)
    except ValueError:
        return datetime.min


def load_audit_candidates(
    audit_payload: Dict[str, Any],
    include_detected_via: Optional[Set[str]],
    include_lookup_failures: bool,
) -> List[Dict[str, Any]]:
    by_player: Dict[int, Dict[str, Any]] = {}

    mismatches = audit_payload.get("mismatches", []) or []
    for entry in mismatches:
        try:
            player_id = int(entry.get("player_id"))
            wom_old = int(entry.get("wom_id_stored"))
            wom_new = int(entry.get("wom_id_remote"))
        except (TypeError, ValueError):
            continue

        if wom_old == wom_new:
            continue

        detected_via = str(entry.get("detected_via") or "unknown")
        if include_detected_via and detected_via not in include_detected_via:
            continue

        existing = by_player.get(player_id)
        if existing is None or parse_iso(entry.get("checked_at")) > parse_iso(existing.get("checked_at")):
            by_player[player_id] = {
                "player_id": player_id,
                "wom_id_stored": wom_old,
                "wom_id_remote": wom_new,
                "detected_via": detected_via,
                "checked_at": entry.get("checked_at"),
                "player_name": entry.get("player_name"),
            }

    if include_lookup_failures:
        failures = audit_payload.get("lookup_failures", []) or []
        for entry in failures:
            try:
                player_id = int(entry.get("player_id"))
                wom_old = int(entry.get("wom_id_stored"))
                wom_new = int(entry.get("wom_id_remote"))
            except (TypeError, ValueError):
                continue
            if wom_old == wom_new:
                continue
            existing = by_player.get(player_id)
            if existing is None or parse_iso(entry.get("checked_at")) > parse_iso(existing.get("checked_at")):
                by_player[player_id] = {
                    "player_id": player_id,
                    "wom_id_stored": wom_old,
                    "wom_id_remote": wom_new,
                    "detected_via": "lookup_failures",
                    "checked_at": entry.get("checked_at"),
                    "player_name": entry.get("player_name"),
                }

    return sorted(by_player.values(), key=lambda x: x["player_id"])


def discover_player_refs(session) -> List[Tuple[str, str]]:
    """
    Discover all table columns that reference players.player_id.
    Also includes known non-FK legacy table columns by convention.
    """
    insp = inspect(session.bind)
    refs: Set[Tuple[str, str]] = set()

    for table_name in insp.get_table_names():
        for fk in insp.get_foreign_keys(table_name):
            if fk.get("referred_table") != "players":
                continue
            constrained_cols = fk.get("constrained_columns") or []
            referred_cols = fk.get("referred_columns") or []
            for constrained_col, referred_col in zip(constrained_cols, referred_cols):
                if referred_col == "player_id":
                    refs.add((table_name, constrained_col))

    # Legacy/non-FK table known to store player_id.
    for table_name, col_name in [("player_loot_data", "player_id")]:
        try:
            cols = {c["name"] for c in insp.get_columns(table_name)}
        except SQLAlchemyError:
            continue
        if col_name in cols:
            refs.add((table_name, col_name))

    return sorted(refs)


def unique_constraints_with_column(insp, table_name: str, col_name: str) -> List[Tuple[str, ...]]:
    constraints: Set[Tuple[str, ...]] = set()

    for uq in insp.get_unique_constraints(table_name) or []:
        cols = tuple((uq.get("column_names") or []))
        if col_name in cols:
            constraints.add(cols)

    for idx in insp.get_indexes(table_name) or []:
        if not idx.get("unique"):
            continue
        cols = tuple((idx.get("column_names") or []))
        if col_name in cols:
            constraints.add(cols)

    return sorted(constraints)


def count_rows_for_player(session, table_name: str, col_name: str, player_id: int) -> int:
    sql = text(
        f"SELECT COUNT(*) AS c FROM {quote_ident(table_name)} "
        f"WHERE {quote_ident(col_name)} = :player_id"
    )
    return int(session.execute(sql, {"player_id": player_id}).scalar() or 0)


def dedupe_conflicts_for_unique_constraint(
    session,
    table_name: str,
    player_col: str,
    from_player_id: int,
    to_player_id: int,
    unique_cols: Sequence[str],
    apply: bool,
) -> int:
    """
    Delete source rows that would violate a unique constraint after reassignment.
    Returns number of rows deleted (or would be deleted in dry-run).
    """
    other_cols = [c for c in unique_cols if c != player_col]
    if not other_cols:
        return 0

    on_parts = [f"s.{quote_ident(player_col)} = :from_id", f"t.{quote_ident(player_col)} = :to_id"]
    for c in other_cols:
        # Null-safe equality in MySQL
        on_parts.append(f"s.{quote_ident(c)} <=> t.{quote_ident(c)}")
    on_sql = " AND ".join(on_parts)
    table_q = quote_ident(table_name)

    count_sql = text(f"SELECT COUNT(*) FROM {table_q} s JOIN {table_q} t ON {on_sql}")
    duplicate_count = int(
        session.execute(count_sql, {"from_id": from_player_id, "to_id": to_player_id}).scalar() or 0
    )
    if duplicate_count == 0:
        return 0

    if apply:
        delete_sql = text(f"DELETE s FROM {table_q} s JOIN {table_q} t ON {on_sql}")
        session.execute(delete_sql, {"from_id": from_player_id, "to_id": to_player_id})
    return duplicate_count


def reassign_player_fk_column(
    session,
    insp,
    table_name: str,
    col_name: str,
    from_player_id: int,
    to_player_id: int,
    apply: bool,
) -> Dict[str, Any]:
    before = count_rows_for_player(session, table_name, col_name, from_player_id)
    if before == 0:
        return {"table": table_name, "column": col_name, "before": 0, "updated": 0, "deduped": 0}

    deduped_total = 0
    for unique_cols in unique_constraints_with_column(insp, table_name, col_name):
        deduped_total += dedupe_conflicts_for_unique_constraint(
            session=session,
            table_name=table_name,
            player_col=col_name,
            from_player_id=from_player_id,
            to_player_id=to_player_id,
            unique_cols=unique_cols,
            apply=apply,
        )

    if apply:
        update_sql = text(
            f"UPDATE {quote_ident(table_name)} "
            f"SET {quote_ident(col_name)} = :to_id "
            f"WHERE {quote_ident(col_name)} = :from_id"
        )
        result = session.execute(update_sql, {"to_id": to_player_id, "from_id": from_player_id})
        updated = int(result.rowcount or 0)
    else:
        # In dry-run, estimate updates as rows left after dedupe.
        updated = max(0, before - deduped_total)

    return {
        "table": table_name,
        "column": col_name,
        "before": before,
        "updated": updated,
        "deduped": deduped_total,
    }


def merge_player_fields(source: Player, target: Player) -> Dict[str, Any]:
    """
    Move useful metadata from target -> source when safe.
    Source is the row we keep (historical row).
    """
    notes: Dict[str, Any] = {}

    if not source.account_hash and target.account_hash:
        source.account_hash = target.account_hash
        notes["account_hash"] = "copied_from_target"
    elif source.account_hash and target.account_hash and source.account_hash != target.account_hash:
        notes["account_hash_conflict"] = "different_non_null_hashes"

    if source.user_id is None and target.user_id is not None:
        source.user_id = target.user_id
        notes["user_id"] = "copied_from_target"
    elif source.user_id is not None and target.user_id is not None and source.user_id != target.user_id:
        notes["user_id_conflict"] = "kept_source_user_id"

    source.log_slots = max(int(source.log_slots or 0), int(target.log_slots or 0))
    source.total_level = max(int(source.total_level or 0), int(target.total_level or 0))
    source.hidden = bool(source.hidden and target.hidden)
    notes["player_name"] = "kept_source_name"

    return notes


def run(args: argparse.Namespace) -> int:
    ensure_parent_dir(args.report_file)

    if not args.audit_file.exists():
        logging.error("Audit file not found: %s", args.audit_file)
        return 1

    with args.audit_file.open("r", encoding="utf-8") as handle:
        audit_payload = json.load(handle)

    include_detected_via = set(args.include_detected_via) if args.include_detected_via else None
    candidates = load_audit_candidates(
        audit_payload=audit_payload,
        include_detected_via=include_detected_via,
        include_lookup_failures=args.include_lookup_failures,
    )

    if args.player_id:
        wanted = set(args.player_id)
        candidates = [c for c in candidates if int(c["player_id"]) in wanted]
    if args.limit is not None:
        candidates = candidates[: args.limit]

    logging.info(
        "Loaded %s repair candidates from %s (mode=%s)",
        len(candidates),
        args.audit_file,
        "APPLY" if args.apply else "DRY-RUN",
    )

    session = Session()
    insp = inspect(session.bind)
    refs = discover_player_refs(session)
    logging.info("Discovered %s player reference columns.", len(refs))

    stats = defaultdict(int)
    results: List[Dict[str, Any]] = []

    try:
        for c in candidates:
            player_id = int(c["player_id"])
            wom_old = int(c["wom_id_stored"])
            wom_new = int(c["wom_id_remote"])
            result: Dict[str, Any] = {
                "player_id": player_id,
                "wom_id_stored": wom_old,
                "wom_id_remote": wom_new,
                "checked_at": c.get("checked_at"),
                "detected_via": c.get("detected_via"),
                "status": "unknown",
            }
            try:
                with session.begin():
                    source = (
                        session.query(Player)
                        .filter(Player.player_id == player_id)
                        .with_for_update()
                        .one_or_none()
                    )
                    if source is None:
                        result["status"] = "skipped_missing_source_player"
                        stats["skipped_missing_source_player"] += 1
                        results.append(result)
                        continue

                    result["source_player_name"] = source.player_name
                    result["source_current_wom_id"] = source.wom_id

                    if int(source.wom_id or 0) != wom_old:
                        result["status"] = "skipped_source_wom_changed_since_audit"
                        stats["skipped_source_wom_changed_since_audit"] += 1
                        results.append(result)
                        continue

                    target = (
                        session.query(Player)
                        .filter(Player.wom_id == wom_new)
                        .with_for_update()
                        .one_or_none()
                    )

                    if target is None:
                        if args.apply:
                            source.wom_id = wom_new
                        result["status"] = "updated_wom_id"
                        stats["updated_wom_id"] += 1
                        results.append(result)
                        continue

                    if target.player_id == source.player_id:
                        result["status"] = "already_correct"
                        stats["already_correct"] += 1
                        results.append(result)
                        continue

                    # Conservatively skip conflicting account_hash merges.
                    if source.account_hash and target.account_hash and source.account_hash != target.account_hash:
                        result["status"] = "skipped_account_hash_conflict"
                        result["target_player_id"] = target.player_id
                        result["source_account_hash"] = source.account_hash
                        result["target_account_hash"] = target.account_hash
                        stats["skipped_account_hash_conflict"] += 1
                        results.append(result)
                        continue

                    # Free unique WOM slot on target row first.
                    if args.apply:
                        target.wom_id = None
                        session.flush()
                        source.wom_id = wom_new

                    ref_updates = []
                    for table_name, col_name in refs:
                        ref_updates.append(
                            reassign_player_fk_column(
                                session=session,
                                insp=insp,
                                table_name=table_name,
                                col_name=col_name,
                                from_player_id=target.player_id,
                                to_player_id=source.player_id,
                                apply=args.apply,
                            )
                        )

                    merge_notes = merge_player_fields(source, target)
                    if "account_hash_conflict" in merge_notes:
                        # Guardrail: should already be prevented above.
                        raise RuntimeError("Unexpected account_hash conflict during merge")

                    remaining_refs = 0
                    for table_name, col_name in refs:
                        remaining_refs += count_rows_for_player(session, table_name, col_name, target.player_id)

                    if remaining_refs == 0:
                        if args.apply:
                            session.delete(target)
                        result["status"] = "merged_into_source_and_deleted_target"
                        stats["merged_into_source_and_deleted_target"] += 1
                    else:
                        result["status"] = "merged_refs_partial_target_retained"
                        stats["merged_refs_partial_target_retained"] += 1

                    result["target_player_id"] = target.player_id
                    result["target_player_name"] = target.player_name
                    result["ref_updates"] = ref_updates
                    result["merge_notes"] = merge_notes
                    result["remaining_target_refs"] = remaining_refs
                    results.append(result)
            except SQLAlchemyError as exc:
                session.rollback()
                result["status"] = "error_sqlalchemy"
                result["error"] = str(exc)
                stats["error_sqlalchemy"] += 1
                results.append(result)
            except Exception as exc:  # pylint: disable=broad-except
                session.rollback()
                result["status"] = "error_exception"
                result["error"] = repr(exc)
                stats["error_exception"] += 1
                results.append(result)
    finally:
        session.close()

    report = {
        "generated_at": datetime.utcnow().isoformat() + "Z",
        "mode": "apply" if args.apply else "dry_run",
        "audit_file": str(args.audit_file),
        "candidate_count": len(candidates),
        "stats": dict(stats),
        "results": results,
    }

    with args.report_file.open("w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=2)

    logging.info("Wrote repair report: %s", args.report_file)
    logging.info("Stats: %s", dict(stats))
    if not args.apply:
        logging.info("Dry-run only. Re-run with --apply to execute changes.")
    return 0


def main(argv: Optional[Iterable[str]] = None) -> int:
    args = parse_args(argv)
    configure_logging()
    return run(args)


if __name__ == "__main__":
    raise SystemExit(main())

